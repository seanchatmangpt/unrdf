#!/usr/bin/env node
/**
 * @file scripts/unrdf-generate-integration.mjs
 * @description Generates package documentation and export metadata from discovered ontology data.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const generatedDir = path.join(projectRoot, 'src', 'generated');
const schemaDir = path.join(projectRoot, 'schema');

function parsePackagesTurtle(turtleContent) {
  const packages = [];
  const packageBlocks = turtleContent.split(/unrdf:.*Package a unrdf:Package/);
  for (const block of packageBlocks.slice(1)) {
    const pkg = {};
    const nameMatch = block.match(/unrdf:packageName "([^"]+)"/);
    if (nameMatch) pkg.name = nameMatch[1];
    const versionMatch = block.match(/unrdf:packageVersion "([^"]+)"/);
    if (versionMatch) pkg.version = versionMatch[1];
    const descriptionMatch = block.match(/unrdf:packageDescription "([^"]+)"/);
    if (descriptionMatch) pkg.description = descriptionMatch[1];
    const tierMatch = block.match(/unrdf:hasTier unrdf:(\w+)Tier/);
    if (tierMatch) pkg.tier = tierMatch[1];
    const dependencyMatches = [...block.matchAll(/unrdf:hasDependency unrdf:(\w+Package)/g)];
    pkg.dependencies = dependencyMatches.map(match => match[1]);
    if (pkg.name) packages.push(pkg);
  }
  return packages;
}

function generatePackageReadme(pkg) {
  const dependencyLinks = pkg.dependencies
    .map(dependency => `- [\`${dependency}\`](../../../../../docs/packages/${dependency.replace(/Package$/, '')}.md)`)
    .join('\n');
  return `# ${pkg.name}

> ${pkg.description}

**Version**: \`${pkg.version}\`
**Tier**: ${pkg.tier}

## Overview

This package provides ${pkg.description.toLowerCase()}.

## Installation

\`\`\`bash
npm install ${pkg.name}
# or
pnpm add ${pkg.name}
\`\`\`

## Usage

See [API Documentation](../../docs/packages/${pkg.name.replace('@unrdf/', '')}.md) for complete API details.

## Dependencies

${dependencyLinks || 'This package has no internal dependencies.'}

## Documentation

- **API Reference**: [docs/](../../docs/)
- **Examples**: [examples/](../../examples/)
- **Contributing**: [CONTRIBUTING.md](../../CONTRIBUTING.md)

## License

Licensed under either of Apache License, Version 2.0 or MIT license at your option.

---

Generated by unrdf sync — ontology-driven code generation
`;
}

function generateTierSummary(packages) {
  const byTier = {};
  for (const pkg of packages) {
    if (!byTier[pkg.tier]) byTier[pkg.tier] = [];
    byTier[pkg.tier].push(pkg);
  }

  let markdown = '# UNRDF Packages by Tier\n\n';
  for (const [tier, tierPackages] of Object.entries(byTier).sort()) {
    markdown += `## ${tier} Tier (${tierPackages.length} packages)\n\n`;
    for (const pkg of tierPackages) {
      markdown += `### ${pkg.name}\n\n${pkg.description}\n\n`;
      markdown += `**Version**: \`${pkg.version}\`\n\n`;
      if (pkg.dependencies.length > 0) {
        markdown += `**Dependencies**: ${pkg.dependencies.join(', ')}\n\n`;
      }
      markdown += '---\n\n';
    }
  }
  return markdown;
}

function writeFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf-8');
}

function manufactureExports(byTier) {
  let content = `/**
 * @file Package Exports Manifest
 * @description Auto-generated package metadata from ontology.
 * Generated by scripts/unrdf-generate-integration.mjs.
 */

`;
  for (const [tier, tierPackages] of Object.entries(byTier)) {
    content += `// ${tier} Tier\nexport const ${tier.toUpperCase()}_PACKAGES = [\n`;
    for (const pkg of tierPackages) {
      content += `  { name: '${pkg.name}', version: '${pkg.version}', tier: '${tier}' },\n`;
    }
    content += `];\n\n`;
  }
  content += `export const ALL_PACKAGES = [
  ...ESSENTIAL_PACKAGES,
  ...EXTENDED_PACKAGES,
  ...OPTIONAL_PACKAGES,
  ...INTERNAL_PACKAGES,
];

export function getPackagesByTier(tier) {
  switch (tier.toUpperCase()) {
    case 'ESSENTIAL': return ESSENTIAL_PACKAGES;
    case 'EXTENDED': return EXTENDED_PACKAGES;
    case 'OPTIONAL': return OPTIONAL_PACKAGES;
    case 'INTERNAL': return INTERNAL_PACKAGES;
    default: return [];
  }
}

export function findPackage(name) {
  return ALL_PACKAGES.find(pkg => pkg.name === name);
}
`;
  return content;
}

function main() {
  console.log('🚀 Starting UNRDF package documentation generation...\n');
  const discoveredPath = path.join(schemaDir, 'packages-discovered.ttl');
  if (!fs.existsSync(discoveredPath)) {
    console.error('❌ packages-discovered.ttl not found. Run unrdf-package-discovery.mjs first.');
    process.exit(1);
  }

  const packages = parsePackagesTurtle(fs.readFileSync(discoveredPath, 'utf-8'));
  if (packages.length === 0) {
    console.error('❌ No package instances were admitted from packages-discovered.ttl.');
    process.exit(1);
  }
  console.log(`📦 Processing ${packages.length} packages...\n`);

  const docsPackagesDir = path.join(projectRoot, 'docs', 'packages');
  fs.mkdirSync(docsPackagesDir, { recursive: true });
  let generatedCount = 0;
  for (const pkg of packages) {
    const readmePath = path.join(docsPackagesDir, `${pkg.name.replace('@unrdf/', '')}.md`);
    writeFile(readmePath, generatePackageReadme(pkg));
    generatedCount += 1;
    if (generatedCount <= 3) console.log(`  ✅ Generated ${readmePath.replace(projectRoot, '.')}`);
  }
  if (packages.length > 3) console.log(`  ✅ ... and ${packages.length - 3} more package docs\n`);

  const byTier = {};
  for (const pkg of packages) {
    if (!byTier[pkg.tier]) byTier[pkg.tier] = [];
    byTier[pkg.tier].push(pkg);
  }

  const tierSummaryPath = path.join(generatedDir, 'TIER_SUMMARY.md');
  writeFile(tierSummaryPath, generateTierSummary(packages));
  console.log(`✅ Generated tier summary: ${tierSummaryPath.replace(projectRoot, '.')}`);

  const exportsPath = path.join(generatedDir, 'package-exports.mjs');
  writeFile(exportsPath, manufactureExports(byTier));
  console.log(`✅ Generated package exports: ${exportsPath.replace(projectRoot, '.')}`);

  const stats = {
    total_packages: packages.length,
    by_tier: Object.fromEntries(Object.entries(byTier).map(([tier, tierPackages]) => [tier, tierPackages.length])),
    generated_files: {
      package_docs: packages.length,
      tier_summary: 1,
      exports_manifest: 1,
    },
  };
  writeFile(path.join(generatedDir, 'GENERATION_STATS.json'), `${JSON.stringify(stats, null, 2)}\n`);

  console.log(`\n📊 Total Packages: ${stats.total_packages}`);
  console.log(`Generated Files: ${generatedCount + 2}`);
  console.log('\n✨ Integration generation complete.');
}

main();
